const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ctx=vm.createContext({});
vm.runInContext(fs.readFileSync('c2pa-inspector.js','utf8'),ctx);
const check=s=>vm.runInContext('c2paValidationLabel('+JSON.stringify(s)+')',ctx);
assert.equal(check('Invalid'),'invalid');
assert.equal(check(' valid '),'valid-untrusted');
assert.equal(check('Trusted'),'unknown');
assert.equal(check('UNKNOWN'),'unknown');
assert.equal(check(null),'unknown');
assert.equal(check({value:'Trusted'}),'unknown');
const summary=s=>{ctx.sample=s;return vm.runInContext('c2paSummarizeStore(sample)',ctx)};
assert.equal(summary(null).status,'absent');
assert.equal(summary({active_manifest:'a',manifests:{a:{title:'Test',claim_generator:'Demo'}},validation_state:'Valid'}).validationState,'valid-untrusted');
assert.equal(summary({active_manifest:'a',manifests:{a:{title:'Test'}},validation_state:'Trusted'}).validationState,'unknown');
assert.equal(summary({active_manifest:'a',manifests:{a:{title:'Test'}}}).validationState,'unknown');
assert.equal(summary({active_manifest:'a',manifests:{a:{}},validation_status:[{code:'assertion.dataHash.mismatch'}]}).validationState,'invalid');
assert.equal(summary({active_manifest:'a',manifests:{a:{title:'Test'}},validation_state:'Invalid'}).validationState,'invalid');
console.log('C2PA conservative validation tests passed');
